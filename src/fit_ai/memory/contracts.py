"""Memory contract. Synchronous on purpose (SQLite calls take milliseconds); async callers use `to_thread`."""
from __future__ import annotations

from typing import Protocol, Sequence

from fit_ai.memory.models import (
    Conversation,
    ConversationTurn,
    MemoryFact,
    MemoryHit,
    MemoryKind,
    TurnRole,
    UserPreference,
)


class MemoryError_(Exception):
    """Base error of the memory layer (named with a trailing underscore: not the builtin MemoryError)."""


class MemoryPolicyError(MemoryError_):
    """The write would violate the memory policy (wrong origin, telemetry as fact, too large...)."""


class MemoryNotFound(MemoryError_):
    pass


class MemoryStorageError(MemoryError_):
    """The database could not be opened or written."""


class MemoryStore(Protocol):
    def create_conversation(self, title: str | None = None) -> Conversation: ...
    def get_conversation(self, conversation_id: str) -> Conversation: ...
    def list_conversations(self, limit: int = 50) -> list[Conversation]: ...
    def add_turn(self, conversation_id: str, role: TurnRole, content: str) -> ConversationTurn: ...
    def recent_turns(self, conversation_id: str, limit: int = 6) -> list[ConversationTurn]: ...

    def set_preference(self, key: str, value: str) -> UserPreference: ...
    def list_preferences(self) -> list[UserPreference]: ...
    def remember_fact(self, content: str, *, ttl_days: float | None = None, origin: str = "user_explicit") -> MemoryFact: ...
    def update_fact(self, fact_id: str, content: str) -> MemoryFact: ...
    def get_fact(self, fact_id: str) -> MemoryFact: ...
    def list_facts(self, limit: int = 100) -> list[MemoryFact]: ...

    def search(self, query: str, *, kinds: Sequence[MemoryKind] = ("fact", "preference"),
               conversation_id: str | None = None, limit: int = 5) -> list[MemoryHit]: ...

    def delete_fact(self, fact_id: str) -> None: ...
    def delete_preference(self, key: str) -> None: ...
    def delete_turn(self, turn_id: str) -> None: ...
    def delete_conversation(self, conversation_id: str) -> None: ...
    def delete_all(self) -> None: ...
    def purge_expired(self) -> int: ...
    def compact(self) -> None: ...
    def close(self) -> None: ...
